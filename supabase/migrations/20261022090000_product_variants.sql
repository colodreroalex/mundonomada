-- Variantes por talla: cada producto tiene una o varias tallas con su propio stock.
-- El precio, la descripción, la imagen y el color siguen en el producto.
-- Los productos existentes pasan a tener una variante con su talla y stock actuales
-- (o "Única" si no tenían talla), y el carrito y los pedidos se enlazan a ella.

create table public.producto_variantes (
  id bigint generated by default as identity primary key,
  producto_id bigint not null references public.productos(id) on delete cascade,
  talla varchar(10) not null check (length(btrim(talla)) > 0),
  stock integer not null default 0 check (stock >= 0 and stock <= 100000),
  orden smallint not null default 0,
  updated_at timestamptz not null default now(),
  unique (producto_id, talla),
  -- Permite que carrito compruebe que la variante es de ese producto
  unique (id, producto_id)
);

create index producto_variantes_producto_idx on public.producto_variantes(producto_id, orden);

create trigger producto_variantes_set_updated_at
before update on public.producto_variantes
for each row execute function app_private.set_updated_at();

insert into public.producto_variantes (producto_id, talla, stock)
select id, coalesce(nullif(btrim(talla), ''), 'Única'), stock
  from public.productos;

-- Carrito: una línea por talla
alter table public.carrito add column variante_id bigint;
update public.carrito c
   set variante_id = v.id
  from public.producto_variantes v
 where v.producto_id = c.producto_id;
alter table public.carrito
  alter column variante_id set not null,
  drop constraint carrito_user_id_producto_id_key,
  add constraint carrito_user_variante_key unique (user_id, variante_id),
  add constraint carrito_variante_fkey foreign key (variante_id, producto_id)
    references public.producto_variantes(id, producto_id) on delete cascade;
create index carrito_variante_idx on public.carrito(variante_id);

-- Pedidos: guardan la variante y una copia de la talla, para que la factura
-- siga mostrando la talla aunque más adelante se borre esa variante
alter table public.order_items
  add column variante_id bigint references public.producto_variantes(id) on delete set null,
  add column talla varchar(10);
update public.order_items oi
   set variante_id = v.id, talla = v.talla
  from public.producto_variantes v
 where v.producto_id = oi.producto_id;
create index order_items_variante_idx on public.order_items(variante_id);

-- El stock y la talla ya solo viven en las variantes
alter table public.productos drop column stock, drop column talla;

alter table public.producto_variantes enable row level security;
revoke all on public.producto_variantes from anon, authenticated;
grant select, insert, update, delete on public.producto_variantes to mundo_nomada_app;
grant usage, select on sequence public.producto_variantes_id_seq to mundo_nomada_app;
create policy backend_producto_variantes on public.producto_variantes
  for all to mundo_nomada_app using (true) with check (true);
